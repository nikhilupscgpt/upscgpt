"""Apply merge_list.csv to a copy of the Neon export, and write the matching SQL for Neon.

Usage:  python3 apply_merges.py [neon_export.json]
Writes: neon_merged.json      — the export with topics changed (input for the builders; Neon itself is untouched)
        topic_redirects.json  — "subjectKey--old_topic" → "subjectKey--new_topic" for topics that disappear
        neon_fixes.sql        — the same topic changes + safe clean-ups, to run in Neon yourself (check the table name first)
"""
import csv
import collections
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Desktop/PYQ Dashboard/data/neon_pyqs_with_solutions.json")
R = json.load(open(SRC, encoding="utf-8"))
moves = list(csv.DictReader(open(os.path.join(HERE, "merge_list.csv"), encoding="utf-8")))
by_id = {r["id"]: r for r in R}

slug = lambda s: re.sub(r"[^a-z0-9]+", "_", s.lower().replace("&", " ")).strip("_")
before = collections.Counter((r["subject"], r["topic"]) for r in R)
for m in moves:
    r = by_id[m["id"]]
    assert r["topic"] == m["current_topic"], f"{m['id']}: export says {r['topic']}, list says {m['current_topic']}"
    r["subject"], r["topic"] = m["new_subject"], m["new_topic"]
after = collections.Counter((r["subject"], r["topic"]) for r in R)
redirect = {}
for (s, t) in before:
    if (s, t) not in after:
        dest = collections.Counter((m["new_subject"], m["new_topic"]) for m in moves if m["subject"] == s and m["current_topic"] == t).most_common(1)[0][0]
        redirect[slug(s) + "--" + slug(t)] = slug(dest[0]) + "--" + slug(dest[1])

json.dump(R, open(os.path.join(HERE, "neon_merged.json"), "w", encoding="utf-8"), ensure_ascii=False)
json.dump(redirect, open(os.path.join(HERE, "topic_redirects.json"), "w"), indent=1)

q = lambda s: "'" + s.replace("'", "''") + "'"
sql = ["-- PYQ clean-up for Neon. Generated by apply_merges.py from merge_list.csv — review before running.",
       "-- The export does not say the table or column names. Edit the two lines below if they differ:",
       "--   table  : \"Question\"   (Prisma default for a model named Question)",
       "--   columns: id, subject, topic, analysis (jsonb) — the field names used in the export",
       "BEGIN;", "", "-- 1. Topic changes (" + str(len(moves)) + " questions)"]
for m in moves:
    sql.append(f'UPDATE "Question" SET subject = {q(m["new_subject"])}, topic = {q(m["new_topic"])} WHERE id = {q(m["id"])} AND topic = {q(m["current_topic"])};')
sql += ["", "-- 2. Empty similar-PYQ placeholders (examYear -5, no stem) → null. The tutor already ignores them; this just cleans the data.",
        """UPDATE "Question" SET analysis = jsonb_set(analysis, '{similarPyq}', 'null'::jsonb)
  WHERE analysis->'similarPyq' IS NOT NULL AND jsonb_typeof(analysis->'similarPyq') = 'object'
    AND COALESCE(analysis->'similarPyq'->>'stem', '') = '';""",
        "", "-- 3. Old 'explanation' copies (the site uses analysis); uncomment if you agree",
        "-- UPDATE \"Question\" SET explanation = NULL WHERE explanation IS NOT NULL AND analysis IS NOT NULL;",
        "", "-- Check before COMMIT: expect " + str(len(before) - len(redirect)) + " topics",
        'SELECT count(DISTINCT (subject, topic)) FROM "Question";', "", "COMMIT;"]
open(os.path.join(HERE, "neon_fixes.sql"), "w", encoding="utf-8").write("\n".join(sql) + "\n")
print(f"{len(moves)} questions moved; topics {len(before)} → {len(after)}; redirects: {redirect}")
